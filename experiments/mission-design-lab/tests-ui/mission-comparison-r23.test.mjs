test('R23 Bennu compares real executed states, keeps one radio, and separates replay from final delta', async () => {
  const [a, b] = runLearningExperiment('bennu').trials.map(trial => trial.result);
  const original = JSON.stringify([a, b]);
  const inspections = [];
  await act(async () => render(React.createElement(ExpeditionComparison, { a, b, onInspect: eventId => inspections.push(eventId) })));
  assert.deepEqual(counts(), [0, 0]);
  assert.deepEqual(row('Registros cientificamente válidos'), ['2 registros', '6 registros', '+4 registros']);
  assert.deepEqual(row('Tempo de contato planejado'), ['240 s', '1.000 s', '+760 s']);
  const scales = [...document.querySelectorAll('.mc-moment-card meter[aria-label^="Energia"]')].map(meter => meter.max);
  assert.deepEqual(scales, [24, 24]);
  await click(/Serviço de solo.*Contatos curtos/);
  assert.equal(scene().dataset.inspection, 'communications');
  const hardware = scene().dataset.radioHardware;
  await click('Ver tentativa A');
  assert.equal(scene().dataset.radioHardware, hardware);
  assert.equal(scene().dataset.inspection, 'communications');
  await click('Investigar B no 3D');
  assert.equal(Number(screen.getByLabelText(/^Tempo comum/).value), 5100);
  assert.equal(Number(scene().dataset.stateTime), 5100);
  assert.equal(b.events.find(event => event.id === inspections.at(-1)).code, 'CONTACT_START');
  await click('Ver estados finais A/B');
  assert.deepEqual(counts(), [2, 6]);
  await click('Voltar ao início A/B');
  assert.deepEqual(counts(), [0, 0]);
  assert.deepEqual(row('Registros cientificamente válidos'), ['2 registros', '6 registros', '+4 registros']);
  assert.equal(JSON.stringify([a, b]), original);
});

