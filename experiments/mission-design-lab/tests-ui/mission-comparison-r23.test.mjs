test('R23 Cerrado links changed processing to scene, clamps ended attempts and resets a new pair', async () => {
  const [a, b] = runLearningExperiment('cerrado').trials.map(trial => trial.result);
  const saved = (id, result) => ({ id, result, createdAt: '2026-11-15T00:00:00Z', inputHash: id, resultHash: id });
  await act(async () => render(React.createElement(CompareDialog, { runs: [saved('B', b), saved('A', a)], onClose() {} })));
  assert.deepEqual(counts(), [0, 0]);
  await click(/Processamento.*BANDAS/);
  assert.equal(scene().dataset.inspection, 'instrument');
  assert.equal(scene().dataset.payloadId, b.config.processing);
  await click('Inspecionar A no 3D');
  assert.equal(scene().dataset.payloadId, a.config.processing);
  await click('Ver estados finais A/B');
  assert.deepEqual(counts(), [a.deliveredRecords, b.deliveredRecords]);
  await click('Inspecionar B no 3D');
  assert.equal(Number(scene().dataset.stateTime), b.completedAtS);
  await click('Investigar esta diferença no 3D');
  assert.ok(Number(screen.getByLabelText(/^Relógio comum A\/B/).value) <= Math.max(a.completedAtS, b.completedAtS));
  await act(async () => fireEvent.change(screen.getByLabelText('Missão A'), { target: { value: 'B' } }));
  assert.equal(Number(screen.getByLabelText(/^Relógio comum A\/B/).value), 0);
  assert.deepEqual(counts(), [0, 0]);
  assert.match(document.querySelector('.compare-note').textContent, /mesma execução/);
});

test('R23 initial energy differences inspect energy instead of misidentifying the launch segment', async () => {
  const config = { launch: 'science', orbit: 'near', duration: 'full', instrument: 'camera', power: 'compact', ground: 'extended' };
  const a = simulateExpedition('bennu', config), b = simulateExpedition('bennu', { ...config, power: 'extended' });
  await act(async () => render(React.createElement(ExpeditionComparison, { a, b })));
  await click('Investigar B no 3D');
  assert.equal(Number(scene().dataset.stateTime), 0);
  assert.equal(scene().dataset.inspection, 'energy');
  assert.equal(scene().dataset.batteryWh, '24');
  await click('Ver tentativa A');
  assert.equal(scene().dataset.inspection, 'energy');
  assert.equal(scene().dataset.batteryWh, '6');
});
