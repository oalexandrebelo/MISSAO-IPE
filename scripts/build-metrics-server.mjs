import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(new URL('../experiments/mission-design-lab/package.json', import.meta.url));
const { build } = require('esbuild');
const root = fileURLToPath(new URL('../', import.meta.url));
const runtime = new URL('../server/metrics/runtime.mjs', import.meta.url);
const { outputFiles: [bundle] } = await build({
  absWorkingDir: root,
  entryPoints: ['server/metrics/entry.mjs'],
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  write: false,
  logLevel: 'warning',
  banner: { js: '// Generated by scripts/build-metrics-server.mjs. Edit server/metrics/entry.mjs and its dependencies.' },
});

// Vercel can build /api separately from the static site, so the Git checkout must contain this bundle.
if (process.argv[2] === '--check') {
  const saved = await readFile(runtime);
  if (!saved.equals(bundle.contents)) throw new Error('Outdated metrics runtime. Run node scripts/build-metrics-server.mjs.');
  console.log('Metrics runtime is current.');
} else {
  await writeFile(runtime, bundle.contents);
  console.log('Metrics runtime bundled at server/metrics/runtime.mjs.');
}
